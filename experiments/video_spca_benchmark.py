# Runtime is retained per seed but is intentionally not bootstrapped: wall-clock
# measurements are not deterministic scientific outcomes.  All metrics below
# are deterministic functions of a fixed dataset and fitted result.
CORE_METRICS = (
    "observed_reconstruction_error",
    "clean_reconstruction_error",
    "observed_explained_variance",
    "achieved_sparsity",
    "subspace_error",
    "axis_component_mean_abs_correlation",
    "loading_component_mean_abs_correlation",
    "temporal_score_mean_abs_correlation",
    "support_precision",
    "support_recall",
    "support_f1",
)

CONVERGENCE_FIELDS = (
    "converged",
    "n_iter",
    "final_stationarity",
    "status",
)

_PER_SEED_FIELDS = (
    "seed_manifest_sha256",
    "fixed_video_config_sha256",
    "run",
    "run_index",
    "seed",
    "method",
    "data_sha256",
    "dataset_manifest_sha256",
    *CORE_METRICS,
    "runtime_seconds",
    *CONVERGENCE_FIELDS,
    "component_permutation",
    "component_signs",
    "corruption_detection",
    "corruption_detection_at_budget",
    "extra",
)


@dataclass(frozen=True)
class VideoBenchmarkConfig:
    """Fixed video settings plus deterministic repetition/bootstrap settings."""

    video_config: VideoExperimentConfig = field(default_factory=VideoExperimentConfig)
    repeats: int = 5
    base_seed: int = 2025
    methods: tuple[str, ...] = DEFAULT_METHODS
    bootstrap_resamples: int = 2000
    bootstrap_seed: int = 2025


@dataclass(frozen=True)
class VideoBenchmarkResult:
    """In-memory benchmark result; constructing it performs no artifact I/O."""

    config: VideoBenchmarkConfig
    seed_manifest: Mapping[str, Any]
    records: tuple[Mapping[str, Any], ...]
    method_summaries: tuple[Mapping[str, Any], ...]
    paired_summaries: tuple[Mapping[str, Any], ...]


def _integer(value: int, name: str, *, positive: bool) -> int:
    if isinstance(value, (bool, np.bool_)) or not isinstance(value, (int, np.integer)):
        raise TypeError(f"{name} must be an integer")
    integer = int(value)
    if positive and integer <= 0:
        raise ValueError(f"{name} must be positive")
    if not positive and integer < 0:
        raise ValueError(f"{name} must be non-negative")
    return integer


def _bootstrap_count(value: int) -> int:
    count = _integer(value, "bootstrap_resamples", positive=True)
    if count < 2:
        raise ValueError("bootstrap_resamples must be at least 2")
    return count


def _fixed_video_config(config: VideoExperimentConfig) -> dict[str, Any]:
    """Return the settings required to remain identical across generated seeds."""

    fixed = asdict(config)
    fixed.pop("seed")
    return fixed


def _validate_config(config: VideoBenchmarkConfig) -> None:
    _integer(config.repeats, "repeats", positive=True)
    _integer(config.base_seed, "base_seed", positive=False)
    _bootstrap_count(config.bootstrap_resamples)
    _integer(config.bootstrap_seed, "bootstrap_seed", positive=False)
    if not isinstance(config.video_config, VideoExperimentConfig):
        raise TypeError("video_config must be a VideoExperimentConfig")
    _validate_video_experiment_config(config.video_config)
    if not isinstance(config.methods, tuple):
        raise TypeError("methods must be a tuple of canonical method names")
    if not config.methods:
        raise ValueError("methods must contain at least one method")
    if len(set(config.methods)) != len(config.methods):
        raise ValueError("methods contains duplicates")
    unknown = sorted(set(config.methods) - set(DEFAULT_METHODS))
    if unknown:
        raise ValueError(f"unknown video methods: {unknown}")
    if "PCA" not in config.methods:
        raise ValueError(
            "methods must include PCA for paired method-minus-PCA summaries"
        )


def _generation_manifest(config: VideoBenchmarkConfig) -> dict[str, Any]:
    fixed_video_config = _fixed_video_config(config.video_config)
    fixed_video_config_sha256 = canonical_sha256(fixed_video_config)
    return make_seed_manifest(
        config.base_seed,
        config.repeats,
        namespace="video-spca-benchmark-v1",
        metadata={
            "fixed_video_config_excluding_seed": fixed_video_config,
            "fixed_video_config_sha256": fixed_video_config_sha256,
            "seed_source": "seed_manifest.seeds[run_index]",
            "methods": list(config.methods),
            "bootstrap_policy": {
                "unit": "seed",
                "difference": "method_minus_pca",
                "interval": "percentile_95",
                "resamples": int(config.bootstrap_resamples),
                "seed": int(config.bootstrap_seed),
                "metrics": list(CORE_METRICS),
                "runtime_included": False,
                "unqualified_runs_retained": True,
                "inference_requires_every_pair_converged": True,
            },
            "hyperparameter_selection": "none_fixed_predeclared_configuration",
        },
    )


def _python_scalar(value: Any) -> Any:
    if isinstance(value, (np.integer, np.floating, np.bool_)):
        return value.item()
    return value


def _normalize_zero_corruption_detection(
    record: dict[str, Any], *, zero_corruption: bool
) -> None:
    """Map only mathematically undefined zero-corruption ranking metrics to null.

    AUROC and average precision are undefined when the generated truth contains
    no positive corruption cells.  That is a declared nullable data contract,
    not a general license to erase non-finite solver diagnostics.
    """

    if not zero_corruption:
        return
    for field_name in ("corruption_detection", "corruption_detection_at_budget"):
        value = record.get(field_name)
        if not isinstance(value, Mapping):
            continue
        normalized = dict(value)
        for metric in ("roc_auc", "average_precision"):
            item = normalized.get(metric)
            if isinstance(item, (np.floating, float)) and np.isnan(float(item)):
                normalized[metric] = None
        record[field_name] = normalized


def _record_from_report(
    report: MethodReport,
    *,
    run_index: int,
    seed: int,
    fixed_video_config_sha256: str,
    zero_corruption: bool,
) -> dict[str, Any]:
    # Keep the complete single-run MethodReport in JSON so the multi-seed
    # wrapper never weakens its evidence (notably outlier-budget and randomized
    # diagnostics).  The common scalar fields remain flat for tidy summaries.
    record: dict[str, Any] = {
        "fixed_video_config_sha256": fixed_video_config_sha256,
        "run": int(run_index),
        "run_index": int(run_index),
        "seed": int(seed),
        **asdict(report),
    }
    _normalize_zero_corruption_detection(
        record,
        zero_corruption=zero_corruption,
    )
    return {key: _python_scalar(value) for key, value in record.items()}


def _pair_key(record: Mapping[str, Any]) -> tuple[int, int]:
    if "run" not in record and "run_index" not in record:
        raise KeyError("record must contain run or run_index")
    run = int(record.get("run", record.get("run_index")))
    if "run" in record and "run_index" in record:
        if run != int(record["run_index"]):
            raise ValueError("record run and run_index disagree")
    return run, int(record["seed"])


def _records_by_method(
    records: Sequence[Mapping[str, Any]],
) -> dict[str, dict[tuple[int, int], Mapping[str, Any]]]:
    grouped: dict[str, dict[tuple[int, int], Mapping[str, Any]]] = {}
    for record in records:
        method = str(record["method"])
        pair = _pair_key(record)
        method_records = grouped.setdefault(method, {})
        if pair in method_records:
            raise ValueError(f"duplicate record for method {method!r} and pair {pair}")
        method_records[pair] = record
    return grouped


def _finite_metric(
    record: Mapping[str, Any],
    metric: str,
    *,
    method: str,
    pair: tuple[int, int],
) -> float:
    if metric not in record:
        raise ValueError(
            f"missing metric {metric!r} for method {method!r} at pair {pair}"
        )
    try:
        value = float(record[metric])
    except (TypeError, ValueError) as error:
        raise ValueError(
            f"metric {metric!r} must be finite for method {method!r} at pair {pair}"
        ) from error
    if not np.isfinite(value):
        raise ValueError(
            f"metric {metric!r} must be finite for method {method!r} at pair {pair}"
        )
    return value


def summarize_method_metrics(
    records: Sequence[Mapping[str, Any]],
) -> list[dict[str, Any]]:
    """Return absolute per-method mean/std, including PCA and descriptive runtime."""

    grouped = _records_by_method(records)
    summaries: list[dict[str, Any]] = []
    for method in sorted(grouped):
        method_records = grouped[method]
        pair_keys = sorted(method_records)
        converged_values: list[bool] = []
        for pair in pair_keys:
            converged = method_records[pair].get("converged")
            if not isinstance(converged, (bool, np.bool_)):
                raise ValueError(
                    f"converged must be boolean for method {method!r} at pair {pair}"
                )
            converged_values.append(bool(converged))
        converged_count = int(sum(converged_values))
        n_seeds = len(pair_keys)
        for metric in (*CORE_METRICS, "runtime_seconds"):
            values = np.asarray(
                [
                    _finite_metric(
                        method_records[pair], metric, method=method, pair=pair
                    )
                    for pair in pair_keys
                ],
                dtype=np.float64,
            )
            summaries.append(
                {
                    "method": method,
                    "metric": metric,
                    "n_seeds": n_seeds,
                    "mean": float(np.mean(values)),
                    "std": float(np.std(values, ddof=1)) if n_seeds > 1 else 0.0,
                    "converged_count": converged_count,
                    "convergence_rate": converged_count / n_seeds,
                    "metric_scope": (
                        "descriptive_wall_clock_only"
                        if metric == "runtime_seconds"
                        else "deterministic_fixed_seed_metric"
                    ),
                }
            )
    return summaries


def _bootstrap_indices(
    pair_keys: Sequence[tuple[int, int]],
    *,
    resamples: int,
    seed: int,
) -> np.ndarray:
    """Build a row-order-independent seed-level resampling plan."""

    digest = canonical_sha256(
        {
            "namespace": "video-spca-paired-bootstrap-v1",
            "bootstrap_seed": int(seed),
            "pair_keys": [list(pair) for pair in pair_keys],
        }
    )
    digest_words = np.frombuffer(bytes.fromhex(digest)[:16], dtype="<u4")
    seed_words = (int(seed) & 0xFFFFFFFF, (int(seed) >> 32) & 0xFFFFFFFF)
    sequence = np.random.SeedSequence([*seed_words, *map(int, digest_words)])
    rng = np.random.default_rng(sequence)
    return rng.integers(
        0,
        len(pair_keys),
        size=(int(resamples), len(pair_keys)),
        endpoint=False,
    )


def summarize_paired_differences(
    records: Sequence[Mapping[str, Any]],
    *,
    bootstrap_resamples: int,
    bootstrap_seed: int,
    metrics: Sequence[str] = CORE_METRICS,
) -> list[dict[str, Any]]:
    """Summarize seed-paired ``method - PCA`` differences with bootstrap CIs."""

    bootstrap_resamples = _bootstrap_count(bootstrap_resamples)
    bootstrap_seed = _integer(bootstrap_seed, "bootstrap_seed", positive=False)
    if not metrics or len(set(metrics)) != len(metrics):
        raise ValueError("metrics must contain unique metric names")
    grouped = _records_by_method(records)
    if "PCA" not in grouped:
        raise ValueError("records must contain a PCA baseline")
    baseline = grouped["PCA"]
    baseline_pairs = set(baseline)
    summaries: list[dict[str, Any]] = []

    for method in sorted(set(grouped) - {"PCA"}):
        method_records = grouped[method]
        method_pairs = set(method_records)
        if method_pairs != baseline_pairs:
            missing = sorted(baseline_pairs - method_pairs)
            extra = sorted(method_pairs - baseline_pairs)
            raise ValueError(
                f"method {method!r} is not paired with PCA; "
                f"missing pairs={missing}, extra pairs={extra}"
            )
        pair_keys = sorted(baseline_pairs)
        for pair in pair_keys:
            method_row = method_records[pair]
            baseline_row = baseline[pair]
            for provenance_field in (
                "data_sha256",
                "dataset_manifest_sha256",
                "fixed_video_config_sha256",
                "seed_manifest_sha256",
            ):
                method_has = provenance_field in method_row
                baseline_has = provenance_field in baseline_row
                if not method_has or not baseline_has:
                    raise ValueError(
                        f"method {method!r} and PCA must both contain "
                        f"{provenance_field} for pair {pair}"
                    )
                if method_row[provenance_field] != baseline_row[provenance_field]:
                    raise ValueError(
                        f"method {method!r} and PCA have different "
                        f"{provenance_field} for pair {pair}"
                    )

        pair_qualified: list[bool] = []
        for pair in pair_keys:
            method_converged = method_records[pair].get("converged")
            baseline_converged = baseline[pair].get("converged")
            if not isinstance(method_converged, (bool, np.bool_)) or not isinstance(
                baseline_converged, (bool, np.bool_)
            ):
                raise ValueError(
                    f"method {method!r} and PCA must contain boolean converged "
                    f"flags for pair {pair}"
                )
            pair_qualified.append(bool(method_converged) and bool(baseline_converged))
        qualified_pairs = int(sum(pair_qualified))
        convergence_qualified = qualified_pairs == len(pair_keys)

        for metric in metrics:
            differences: list[float] = []
            for pair in pair_keys:
                method_float = _finite_metric(
                    method_records[pair], metric, method=method, pair=pair
                )
                baseline_float = _finite_metric(
                    baseline[pair], metric, method="PCA", pair=pair
                )
                differences.append(method_float - baseline_float)

            paired = np.asarray(differences, dtype=np.float64)
            n_pairs = int(paired.size)
            mean_difference = float(np.mean(paired)) if n_pairs else None
            std_difference = (
                float(np.std(paired, ddof=1))
                if n_pairs >= 2
                else (0.0 if n_pairs == 1 else None)
            )
            if n_pairs >= 2:
                indices = _bootstrap_indices(
                    pair_keys,
                    resamples=bootstrap_resamples,
                    seed=bootstrap_seed,
                )
                bootstrap_means = np.mean(paired[indices], axis=1)
                ci_low, ci_high = (
                    float(value)
                    for value in np.quantile(bootstrap_means, (0.025, 0.975))
                )
                ci_status = (
                    "ok"
                    if convergence_qualified
                    else "unqualified_fixed_budget_runs_included"
                )
            else:
                ci_low = None
                ci_high = None
                ci_status = "insufficient_pairs"

            summaries.append(
                {
                    "method": method,
                    "metric": metric,
                    "baseline_method": "PCA",
                    "difference_direction": "method_minus_pca",
                    "n_pairs": n_pairs,
                    "mean_difference": mean_difference,
                    "std_difference": std_difference,
                    "bootstrap_ci95_low": ci_low,
                    "bootstrap_ci95_high": ci_high,
                    "bootstrap_ci95_status": ci_status,
                    "inference_qualified": n_pairs >= 2 and convergence_qualified,
                    "qualified_pairs": qualified_pairs,
                    "unqualified_pairs": n_pairs - qualified_pairs,
                    "summary_population": (
                        "all_preregistered_pairs_including_unqualified_fixed_budget_runs"
                    ),
                    "bootstrap_resamples": bootstrap_resamples,
                    "bootstrap_seed": bootstrap_seed,
                    "bootstrap_unit": "seed",
                }
            )
    return summaries


def run_video_benchmark(
    config: VideoBenchmarkConfig | None = None,
) -> VideoBenchmarkResult:
    """Run all pre-declared methods once on each deterministic video seed."""

    resolved = VideoBenchmarkConfig() if config is None else config
    _validate_config(resolved)
    fixed_video_config = _fixed_video_config(resolved.video_config)
    fixed_video_config_sha256 = canonical_sha256(fixed_video_config)
    manifest = _generation_manifest(resolved)

    records: list[dict[str, Any]] = []
    run_provenance: list[dict[str, Any]] = []
    for run_index, raw_seed in enumerate(manifest["seeds"]):
        seed = int(raw_seed)
        run_config = replace(resolved.video_config, seed=seed)
        if _fixed_video_config(run_config) != fixed_video_config:
            raise RuntimeError("video configuration changed across seeds")
        experiment = run_video_experiment(run_config, methods=resolved.methods)
        if tuple(experiment.reports) != resolved.methods:
            raise RuntimeError("video runner returned methods in an unexpected order")
        dataset_manifest_shas = {
            report.dataset_manifest_sha256 for report in experiment.reports.values()
        }
        data_shas = {report.data_sha256 for report in experiment.reports.values()}
        if len(dataset_manifest_shas) != 1 or len(data_shas) != 1:
            raise RuntimeError(
                "methods within a seed were not evaluated on shared data"
            )
        dataset_manifest_sha256 = next(iter(dataset_manifest_shas))
        data_sha256 = next(iter(data_shas))
        if data_sha256 != experiment.dataset.digest:
            raise RuntimeError("reported data digest does not match the video dataset")
        run_provenance.append(
            {
                "run": run_index,
                "run_index": run_index,
                "seed": seed,
                "data_sha256": data_sha256,
                "dataset_manifest_sha256": dataset_manifest_sha256,
            }
        )
        for method in resolved.methods:
            records.append(
                _record_from_report(
                    experiment.reports[method],
                    run_index=run_index,
                    seed=seed,
                    fixed_video_config_sha256=fixed_video_config_sha256,
                    zero_corruption=resolved.video_config.corruption_fraction == 0.0,
                )
            )

    generation_manifest_sha256 = str(manifest["manifest_sha256"])
    manifest_body = dict(manifest)
    manifest_body.pop("manifest_sha256")
    manifest_body["generation_manifest_sha256"] = generation_manifest_sha256
    manifest_body["run_provenance"] = run_provenance
    manifest_body["manifest_sha256"] = canonical_sha256(manifest_body)
    final_manifest_sha256 = str(manifest_body["manifest_sha256"])
    for record in records:
        record["seed_manifest_sha256"] = final_manifest_sha256

    method_summaries = summarize_method_metrics(records)
    paired_summaries = summarize_paired_differences(
        records,
        bootstrap_resamples=resolved.bootstrap_resamples,
        bootstrap_seed=resolved.bootstrap_seed,
    )
    return VideoBenchmarkResult(
        config=resolved,
        seed_manifest=manifest_body,
        records=tuple(records),
        method_summaries=tuple(method_summaries),
        paired_summaries=tuple(paired_summaries),
    )


def run_benchmark(
    config: VideoBenchmarkConfig | None = None,
) -> VideoBenchmarkResult:
    """Compatibility alias using the naming of ``spca_benchmark.py``."""

    return run_video_benchmark(config)


def _reject_nonfinite_numbers(value: Any, *, location: str = "root") -> None:
    if isinstance(value, Mapping):
        for key, item in value.items():
            _reject_nonfinite_numbers(key, location=f"{location}.<key>")
            _reject_nonfinite_numbers(item, location=f"{location}.{key}")
    elif isinstance(value, (list, tuple)):
        for index, item in enumerate(value):
            _reject_nonfinite_numbers(item, location=f"{location}[{index}]")
    elif isinstance(value, np.ndarray):
        _reject_nonfinite_numbers(value.tolist(), location=location)
    elif isinstance(value, (np.floating, float)) and not np.isfinite(float(value)):
        raise ValueError(f"number must be finite at {location}")


def _require_sha256(value: Any, *, name: str) -> str:
    if (
        not isinstance(value, str)
        or len(value) != 64
        or any(character not in "0123456789abcdef" for character in value)
    ):
        raise ValueError(f"{name} must be a lowercase hexadecimal SHA-256 digest")
    return value


def _validate_result(result: VideoBenchmarkResult) -> None:
    """Rebuild every manifest and summary contract before artifact creation."""

    _validate_config(result.config)
    _reject_nonfinite_numbers(_config_payload(result.config), location="config")
    _reject_nonfinite_numbers(result.seed_manifest, location="seed_manifest")
    _reject_nonfinite_numbers(result.records, location="records")
    _reject_nonfinite_numbers(result.method_summaries, location="method_summaries")
    _reject_nonfinite_numbers(result.paired_summaries, location="paired_summaries")

    generation_manifest = _generation_manifest(result.config)
    generation_digest = _require_sha256(
        generation_manifest["manifest_sha256"],
        name="generation manifest SHA-256",
    )
    seeds = tuple(int(seed) for seed in generation_manifest["seeds"])
    expected_pairs = tuple(enumerate(seeds))
    fixed_config_sha256 = canonical_sha256(
        _fixed_video_config(result.config.video_config)
    )

    if not isinstance(result.records, tuple):
        raise TypeError("records must be a tuple")
    expected_record_count = len(expected_pairs) * len(result.config.methods)
    if len(result.records) != expected_record_count:
        raise ValueError("per-seed video records are missing or duplicated")

    records_by_identity: dict[tuple[int, int, str], Mapping[str, Any]] = {}
    expected_fields = set(_PER_SEED_FIELDS)
    for record_index, record in enumerate(result.records):
        location = f"records[{record_index}]"
        if not isinstance(record, Mapping):
            raise TypeError(f"{location} must be a mapping")
        if set(record) != expected_fields:
            missing = sorted(expected_fields - set(record))
            extra = sorted(set(record) - expected_fields)
            raise ValueError(
                f"{location} schema mismatch; missing={missing}, extra={extra}"
            )
        method = record["method"]
        if not isinstance(method, str) or method not in result.config.methods:
            raise ValueError(f"{location}.method is not predeclared")
        run = _integer(record["run"], f"{location}.run", positive=False)
        run_index = _integer(
            record["run_index"], f"{location}.run_index", positive=False
        )
        seed = _integer(record["seed"], f"{location}.seed", positive=False)
        if run != run_index or run >= len(seeds) or seed != seeds[run]:
            raise ValueError(
                f"{location} run/seed identity disagrees with its manifest"
            )
        identity = (run, seed, method)
        if identity in records_by_identity:
            raise ValueError(f"duplicate per-seed video record: {identity}")
        records_by_identity[identity] = record

        if (
            _require_sha256(
                record["fixed_video_config_sha256"],
                name=f"{location}.fixed_video_config_sha256",
            )
            != fixed_config_sha256
        ):
            raise ValueError(f"{location} has a mismatched fixed video config")
        _require_sha256(record["data_sha256"], name=f"{location}.data_sha256")
        _require_sha256(
            record["dataset_manifest_sha256"],
            name=f"{location}.dataset_manifest_sha256",
        )
        _require_sha256(
            record["seed_manifest_sha256"],
            name=f"{location}.seed_manifest_sha256",
        )
        for metric in (*CORE_METRICS, "runtime_seconds"):
            metric_value = _finite_metric(
                record,
                metric,
                method=method,
                pair=(run, seed),
            )
            if metric == "runtime_seconds" and metric_value < 0.0:
                raise ValueError(f"{location}.runtime_seconds must be non-negative")
        if not isinstance(record["converged"], (bool, np.bool_)):
            raise TypeError(f"{location}.converged must be boolean")
        _integer(record["n_iter"], f"{location}.n_iter", positive=True)
        stationarity = record["final_stationarity"]
        if stationarity is None:
            if method != "PCA":
                raise ValueError(
                    f"{location}.final_stationarity may be null only for PCA"
                )
        else:
            stationarity_value = _finite_metric(
                record,
                "final_stationarity",
                method=method,
                pair=(run, seed),
            )
            if stationarity_value < 0.0:
                raise ValueError(f"{location}.final_stationarity must be non-negative")
        if not isinstance(record["status"], str) or not record["status"]:
            raise ValueError(f"{location}.status must be a non-empty string")

        permutation = record["component_permutation"]
        signs = record["component_signs"]
        component_count = result.config.video_config.n_components
        if (
            not isinstance(permutation, (list, tuple))
            or len(permutation) != component_count
        ):
            raise ValueError(f"{location}.component_permutation has the wrong length")
        if not isinstance(signs, (list, tuple)) or len(signs) != component_count:
            raise ValueError(f"{location}.component_signs has the wrong length")
        for index, value in enumerate(permutation):
            _integer(
                value, f"{location}.component_permutation[{index}]", positive=False
            )
        if sorted(int(value) for value in permutation) != list(range(component_count)):
            raise ValueError(
                f"{location}.component_permutation must be a complete permutation"
            )
        for index, value in enumerate(signs):
            if isinstance(value, (bool, np.bool_)) or not isinstance(
                value, (int, np.integer)
            ):
                raise TypeError(
                    f"{location}.component_signs[{index}] must be an integer"
                )
            if int(value) not in {-1, 1}:
                raise ValueError(f"{location}.component_signs[{index}] must be -1 or 1")
        for field_name in (
            "corruption_detection",
            "corruption_detection_at_budget",
        ):
            value = record[field_name]
            if value is not None and not isinstance(value, Mapping):
                raise TypeError(f"{location}.{field_name} must be a mapping or null")
        if not isinstance(record["extra"], Mapping):
            raise TypeError(f"{location}.extra must be a mapping")

    expected_identities = {
        (run, seed, method)
        for run, seed in expected_pairs
        for method in result.config.methods
    }
    if set(records_by_identity) != expected_identities:
        missing = sorted(expected_identities - set(records_by_identity))
        extra = sorted(set(records_by_identity) - expected_identities)
        raise ValueError(
            f"per-seed video record matrix is incomplete; missing={missing}, extra={extra}"
        )

    run_provenance: list[dict[str, Any]] = []
    for run, seed in expected_pairs:
        method_rows = [
            records_by_identity[(run, seed, method)] for method in result.config.methods
        ]
        data_hashes = {str(row["data_sha256"]) for row in method_rows}
        dataset_hashes = {str(row["dataset_manifest_sha256"]) for row in method_rows}
        if len(data_hashes) != 1 or len(dataset_hashes) != 1:
            raise ValueError(f"methods are not paired on one dataset for run {run}")
        run_provenance.append(
            {
                "run": run,
                "run_index": run,
                "seed": seed,
                "data_sha256": next(iter(data_hashes)),
                "dataset_manifest_sha256": next(iter(dataset_hashes)),
            }
        )
    if len({row["data_sha256"] for row in run_provenance}) != len(run_provenance):
        raise ValueError("video data SHA-256 values must be unique across seeds")
    if len({row["dataset_manifest_sha256"] for row in run_provenance}) != len(
        run_provenance
    ):
        raise ValueError("video dataset manifests must be unique across seeds")

    expected_manifest = dict(generation_manifest)
    expected_manifest.pop("manifest_sha256")
    expected_manifest["generation_manifest_sha256"] = generation_digest
    expected_manifest["run_provenance"] = run_provenance
    expected_manifest["manifest_sha256"] = canonical_sha256(expected_manifest)
    if not verify_seed_manifest(result.seed_manifest):
        raise ValueError("video seed manifest hash mismatch")
    if dict(result.seed_manifest) != expected_manifest:
        raise ValueError("video seed manifest does not bind config and run provenance")
    final_manifest_sha256 = str(expected_manifest["manifest_sha256"])
    if any(
        record["seed_manifest_sha256"] != final_manifest_sha256
        for record in result.records
    ):
        raise ValueError("per-seed records do not bind the final video manifest")

    expected_method_summaries = tuple(summarize_method_metrics(result.records))
    if tuple(result.method_summaries) != expected_method_summaries:
        raise ValueError("method summaries do not match the per-seed video records")
    expected_paired_summaries = tuple(
        summarize_paired_differences(
            result.records,
            bootstrap_resamples=result.config.bootstrap_resamples,
            bootstrap_seed=result.config.bootstrap_seed,
        )
    )
    if tuple(result.paired_summaries) != expected_paired_summaries:
        raise ValueError("paired summaries do not match the per-seed video records")


def _json_safe(value: Any) -> Any:
    if isinstance(value, Mapping):
        return {str(key): _json_safe(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_safe(item) for item in value]
    if isinstance(value, np.ndarray):
        return _json_safe(value.tolist())
    if isinstance(value, (np.integer, np.floating, np.bool_)):
        value = value.item()
    if isinstance(value, float) and not np.isfinite(value):
        raise ValueError("non-finite numbers are forbidden in video artifacts")
    return value


