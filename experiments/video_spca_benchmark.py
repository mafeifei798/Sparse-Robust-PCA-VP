#!/usr/bin/env python3
"""Deterministic multi-seed paired benchmark for the synthetic video study.

Every seed is generated by a content-addressed seed manifest.  Within one
seed, :func:`experiments.video_spca.run_video_experiment` fits every requested
method to the same generated video.  The benchmark keeps one fixed,
pre-declared solver configuration across seeds; ground truth is used only by
the existing post-fit scorer and never to choose a hyperparameter or a run.

No file is created unless ``--output-json`` and/or ``--output-csv`` is passed.
"""

